func main() {
	outPath := flag.String("out", "src/settings.generated.ts", "output TypeScript file path")
	flag.Parse()

	var buf bytes.Buffer
	buf.WriteString("// Code generated by go run ./go/cmd/gents; DO NOT EDIT.\n\n")

	emitted := make(map[reflect.Type]bool)
	for _, spec := range rootTypes {
		if err := emitTypeTree(&buf, spec.typ, spec.doc, emitted); err != nil {
			fatalf("generate %s: %v", spec.typ.Name(), err)
		}
	}

	if err := writeDefaults(&buf, settings.DefaultSettings()); err != nil {
		fatalf("generate DEFAULT_SETTINGS: %v", err)
	}

	if err := os.WriteFile(*outPath, buf.Bytes(), 0o644); err != nil {
		fatalf("write %s: %v", *outPath, err)
	}
}

func emitTypeTree(buf *bytes.Buffer, t reflect.Type, doc string, emitted map[reflect.Type]bool) error {
	for t.Kind() == reflect.Ptr || t.Kind() == reflect.Slice || t.Kind() == reflect.Map {
		t = t.Elem()
	}
	if t.Kind() != reflect.Struct || emitted[t] {
		return nil
	}
	emitted[t] = true

	// Emit nested struct dependencies first so interfaces remain well-ordered.
	for field := range t.Fields() {
		if jsonName, _ := parseJSONTag(field); jsonName == "" {
			continue
		}
		if err := emitTypeTree(buf, field.Type, "", emitted); err != nil {
			return err
		}
	}

	if doc == "" {
		doc = fmt.Sprintf("Generated TypeScript representation of Go `settings.%s`.", t.Name())
	}
	if err := writeInterface(buf, t.Name(), doc, t); err != nil {
		return err
	}
	buf.WriteByte('\n')
	return nil
}

func writeInterface(buf *bytes.Buffer, name, doc string, t reflect.Type) error {
	fmt.Fprintf(buf, "/** %s */\n", doc)
	fmt.Fprintf(buf, "export interface %s {\n", name)
	for field := range t.Fields() {
		jsonName, omitempty := parseJSONTag(field)
		if jsonName == "" {
			continue
		}
		tsType, err := goTypeToTS(field.Type)
		if err != nil {
			return fmt.Errorf("field %s: %w", field.Name, err)
		}
		opt := ""
		if omitempty && field.Type.Kind() == reflect.Ptr {
			opt = "?"
		} else if omitempty && field.Type.Kind() == reflect.Slice {
			opt = "?"
		} else if omitempty && (field.Type.Kind() == reflect.String || field.Type.Kind() == reflect.Bool || isNumericKind(field.Type.Kind())) {
			opt = "?"
		}
		fmt.Fprintf(buf, "\t%s%s: %s;\n", jsonName, opt, tsType)
	}
	buf.WriteString("}\n")
	return nil
}

func writeDefaults(buf *bytes.Buffer, defaults settings.PluginSettings) error {
	buf.WriteString("/** Default settings derived from Go's settings.DefaultSettings(). */\n")
	buf.WriteString("export const DEFAULT_SETTINGS: PluginSettings = {\n")

	v := reflect.ValueOf(defaults)
	t := v.Type()
	for i := 0; i < t.NumField(); i++ {
		field := t.Field(i)
		jsonName, _ := parseJSONTag(field)
		if jsonName == "" {
			continue
		}
		valLiteral, err := tsLiteral(v.Field(i).Interface())
		if err != nil {
			return fmt.Errorf("default for %s: %w", field.Name, err)
		}
		fmt.Fprintf(buf, "\t%s: %s,\n", jsonName, valLiteral)
	}
	buf.WriteString("};\n")
	return nil
}

func parseJSONTag(f reflect.StructField) (name string, omitempty bool) {
	tag := f.Tag.Get("json")
	if tag == "-" {
		return "", false
	}
	if tag == "" {
		return f.Name, false
	}
	parts := strings.Split(tag, ",")
	name = parts[0]
	if name == "" {
		name = f.Name
	}
	for _, opt := range parts[1:] {
		if opt == "omitempty" {
			omitempty = true
		}
	}
	return name, omitempty
}

func isNumericKind(k reflect.Kind) bool {
	switch k {
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return true
	default:
		return false
	}
}

func goTypeToTS(t reflect.Type) (string, error) {
	if t.Kind() == reflect.Ptr {
		return goTypeToTS(t.Elem())
	}
	if isNumericKind(t.Kind()) {
		return "number", nil
	}
	switch t.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Slice:
		elem, err := goTypeToTS(t.Elem())
		if err != nil {
			return "", err
		}
		return elem + "[]", nil
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", fmt.Errorf("unsupported map key kind %s", t.Key().Kind())
		}
		valType, err := goTypeToTS(t.Elem())
		if err != nil {
			return "", err
		}
		return "Record<string, " + valType + ">", nil
	case reflect.Struct:
		return t.Name(), nil
	default:
		return "", fmt.Errorf("unsupported Go kind %s", t.Kind())
	}
}

func tsLiteral(val any) (string, error) {
	switch v := val.(type) {
	case string:
		escaped := strings.ReplaceAll(v, `\`, `\\`)
		escaped = strings.ReplaceAll(escaped, `'`, `\'`)
		return "'" + escaped + "'", nil
	case []string:
		parts := make([]string, len(v))
		for i, item := range v {
			lit, err := tsLiteral(item)
			if err != nil {
				return "", err
			}
			parts[i] = lit
		}
		return "[" + strings.Join(parts, ", ") + "]", nil
	default:
		raw, err := json.Marshal(val)
		if err != nil {
			return "", err
		}
		return string(raw), nil
	}
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gents: "+format+"\n", args...)
	os.Exit(1)
}
