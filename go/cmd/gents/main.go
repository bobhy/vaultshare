// Command gents generates TypeScript interfaces and default constants from the
// canonical Go settings and RPC structs so Go and TypeScript share a single
// source of truth.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"reflect"
	"strings"

	"vaultshare/go/settings"
)

